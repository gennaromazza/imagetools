import { generateKeyPairSync } from "node:crypto";
import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const { publicKey, privateKey } = generateKeyPairSync("ed25519");
const publicPem = publicKey.export({ type: "spki", format: "pem" });
const privatePem = privateKey.export({ type: "pkcs8", format: "pem" });
const destination = resolve("apps/filex-desktop/src/license-public-key.ts");
writeFileSync(destination, `// Generated by scripts/setup-filex-attestation-key.mjs. Public verification key only.\nexport const FILEX_LICENSE_PUBLIC_KEY = ${JSON.stringify(publicPem)};\n`, "utf8");
const command = process.platform === "win32" ? "firebase.cmd" : "firebase";
const result = spawnSync(command, ["functions:secrets:set", "FILEX_LICENSE_SIGNING_PRIVATE_KEY", "--project", "gen-lang-client-0321087169", "--force"], {
  input: privatePem,
  stdio: ["pipe", "inherit", "inherit"],
  shell: process.platform === "win32",
});
if (result.status !== 0) process.exit(result.status ?? 1);
console.log(`FileX attestation public key written to ${destination}; private key stored in Secret Manager.`);

